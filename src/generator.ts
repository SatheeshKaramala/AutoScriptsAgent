export type ManualStep =
  | { action: "click"; selector: string }
  | { action: "fill"; selector: string; value: string }
  | { action: "press"; selector: string; key: string }
  | { action: "expectText"; selector: string; text: string }
  | { action: "expectVisible"; selector: string }
  | { action: "expectHidden"; selector: string };

export interface ManualCase {
  title: string;
  steps: ManualStep[];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function requiredString(
  value: unknown,
  description: string,
  allowEmpty = false,
): string {
  if (typeof value !== "string" || (!allowEmpty && value.trim().length === 0)) {
    throw new Error(`${description} must be ${allowEmpty ? "a string" : "a non-empty string"}.`);
  }

  return value;
}

function parseStep(value: unknown, caseIndex: number, stepIndex: number): ManualStep {
  const location = `Case ${caseIndex + 1}, step ${stepIndex + 1}`;
  if (!isRecord(value)) {
    throw new Error(`${location} must be an object.`);
  }

  const action = requiredString(value.action, `${location} action`);
  const selector = requiredString(value.selector, `${location} selector`);

  switch (action) {
    case "click":
    case "expectVisible":
    case "expectHidden":
      return { action, selector };
    case "fill":
      return {
        action,
        selector,
        value: requiredString(value.value, `${location} value`, true),
      };
    case "press":
      return {
        action,
        selector,
        key: requiredString(value.key, `${location} key`),
      };
    case "expectText":
      return {
        action,
        selector,
        text: requiredString(value.text, `${location} text`),
      };
    default:
      throw new Error(
        `${location} has unsupported action "${action}". Supported actions: click, fill, press, expectText, expectVisible, expectHidden.`,
      );
  }
}

export function parseManualCases(value: unknown): ManualCase[] {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error("The cases file must contain a non-empty JSON array.");
  }

  return value.map((item, caseIndex) => {
    const location = `Case ${caseIndex + 1}`;
    if (!isRecord(item)) {
      throw new Error(`${location} must be an object.`);
    }

    const title = requiredString(item.title, `${location} title`);
    if (!Array.isArray(item.steps) || item.steps.length === 0) {
      throw new Error(`${location} steps must be a non-empty array.`);
    }

    return {
      title,
      steps: item.steps.map((step, stepIndex) =>
        parseStep(step, caseIndex, stepIndex),
      ),
    };
  });
}

export function validateBaseUrl(value: string): string {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`Invalid URL "${value}". Provide a full http:// or https:// URL.`);
  }

  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new Error(`Unsupported URL protocol "${url.protocol}". Use http:// or https://.`);
  }

  return url.toString();
}

function renderStep(step: ManualStep): string {
  const locator = `page.locator(${JSON.stringify(step.selector)})`;

  switch (step.action) {
    case "click":
      return `    await ${locator}.click();`;
    case "fill":
      return `    await ${locator}.fill(${JSON.stringify(step.value)});`;
    case "press":
      return `    await ${locator}.press(${JSON.stringify(step.key)});`;
    case "expectText":
      return `    await expect(${locator}).toContainText(${JSON.stringify(step.text)});`;
    case "expectVisible":
      return `    await expect(${locator}).toBeVisible();`;
    case "expectHidden":
      return `    await expect(${locator}).toBeHidden();`;
  }
}

export function renderPlaywrightTests(url: string, cases: ManualCase[]): string {
  const baseUrl = validateBaseUrl(url);
  const tests = cases
    .map(
      (manualCase) => `  test(${JSON.stringify(manualCase.title)}, async ({ page }) => {
    await page.goto(${JSON.stringify(baseUrl)});
${manualCase.steps.map(renderStep).join("\n")}
  });`,
    )
    .join("\n\n");

  return `// Generated by AutoScriptsAgent. Update the cases JSON and regenerate to make changes.
import { expect, test } from "@playwright/test";

test.describe("Generated manual test cases", () => {
${tests}
});
`;
}
